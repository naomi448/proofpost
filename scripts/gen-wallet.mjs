/**
 * Generates the FRESH ProofPost demo wallet and writes its secrets to .env
 * (mode 600, gitignored). Prints ONLY public addresses — never the WIF.
 *
 * This wallet is demo-only and must only ever hold dust (~0.0005–0.001 BCH).
 * Run once:  node scripts/gen-wallet.mjs
 * Refuses to overwrite an existing .env.
 */
import {
  secp256k1,
  hash160,
  encodeCashAddress,
  encodePrivateKeyWif,
  decodePrivateKeyWif,
} from "@bitauth/libauth";
import { randomBytes } from "node:crypto";
import { writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env");

if (existsSync(envPath)) {
  console.error("REFUSING to overwrite existing .env — a demo wallet already exists.");
  process.exit(1);
}

const privateKey = new Uint8Array(randomBytes(32));
const pubkey = secp256k1.derivePublicKeyCompressed(privateKey);
if (typeof pubkey === "string") throw new Error("pubkey derivation failed: " + pubkey);
const pubkeyHash = hash160(pubkey);

const addr = (prefix, type) => {
  const r = encodeCashAddress({ prefix, type, payload: pubkeyHash });
  if (typeof r === "string") throw new Error("address encoding failed: " + r);
  return r.address;
};

const wifMainnet = encodePrivateKeyWif(privateKey, "mainnet");
const wifTestnet = encodePrivateKeyWif(privateKey, "testnet");
if (typeof wifMainnet === "string" && wifMainnet.startsWith("ERROR")) throw new Error(wifMainnet);

// Round-trip sanity: decoding the mainnet WIF must return the same key.
const decoded = decodePrivateKeyWif(wifMainnet);
if (typeof decoded === "string" || !decoded.privateKey.every((b, i) => b === privateKey[i])) {
  throw new Error("WIF round-trip check failed");
}

const mainnetAddress = addr("bitcoincash", "p2pkh");
const mainnetTokenAddress = addr("bitcoincash", "p2pkhWithTokens");
const testnetAddress = addr("bchtest", "p2pkh");
const testnetTokenAddress = addr("bchtest", "p2pkhWithTokens");

const env = [
  "# ProofPost demo wallet secrets — DEMO ONLY, dust balance only.",
  "# Generated by scripts/gen-wallet.mjs. NEVER commit this file.",
  `VITE_DEMO_WIF_MAINNET=${wifMainnet}`,
  `VITE_DEMO_WIF_TESTNET=${wifTestnet}`,
  "",
].join("\n");

writeFileSync(envPath, env, { mode: 0o600 });

console.log("Demo wallet generated. Public addresses (safe to share):");
console.log("  MAINNET address        :", mainnetAddress);
console.log("  MAINNET token address  :", mainnetTokenAddress);
console.log("  TESTNET address        :", testnetAddress);
console.log("  TESTNET token address  :", testnetTokenAddress);
console.log("Secrets written to .env (mode 600, gitignored). WIF not printed.");
